"""
prepare_relax_longitudinal_v2.py

Prepare RELAXDataset for longitudinal personalized stress recognition.

Main design
-----------
Positive (stress=1):
  - IFB contains an explicitly reported stressful-event time.
  - Reconstructed event time must satisfy:
        previous IFB submission < event_time <= current IFB submission
  - Physiology anchor = event_time.

Negative (non-stress=0):
  - IFB has NO reported stressful-event time.
  - current valence >= 4
  - current arousal >= 4   (dataset scale: toward calm)
  - current physical exertion <= 4
  - current mental exertion <= 4
  - optionally exclude negatives close to any valid positive event.
  - Physiology anchor = IFB submission time.

Physiology:
  - search within the 5-minute interval before the anchor;
  - physiological plausibility: 300 <= IBI <= 2000 ms;
  - rolling-median relative-deviation artifact filter: <= 30%;
  - optionally exclude ibi_blocker == True (OFF by default);
  - split only at large timestamp gaps;
  - select the latest 64 retained IBI within a bounded time span;
  - compute the same 32 HRV features used in the WESAD pipeline.

Important:
  - NO global scaling is performed here.
  - StandardScaler / normalization must be fitted on source subjects only
    inside each outer LOSO fold later.
  - This script only prepares raw RR windows + HRV features + chronology.

Expected inputs
---------------
RELAXDataset root:
  <root>/
    data/<user>/ibi_data.parquet
    questionnaire_responses.xlsx  # not required by this script directly

Alignment directory (generated by inspect_relax_dataset.py):
  current_ema_ibi_alignment.csv
  stress_event_ibi_alignment.csv

Outputs
-------
  relax_longitudinal_v2.npz
  relax_longitudinal_v2_manifest.csv
  relax_longitudinal_v2_subject_summary.csv
  relax_longitudinal_v2_rejected.csv
  relax_longitudinal_v2_config.json
"""

